import { readFileSync, writeFileSync } from "node:fs";
import { defineConfig } from "orval";

const input = "./openapi.json";
const format = "oxfmt";
const decimalFieldsFile = "./src/api/generated/decimal-fields.ts";

interface SchemaNode {
  $ref?: string;
  format?: string;
  properties?: Record<string, SchemaNode>;
  items?: SchemaNode;
  oneOf?: SchemaNode[];
}

interface Operation {
  requestBody?: { content?: Record<string, { schema?: SchemaNode }> };
}

interface OpenApiDocument {
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, SchemaNode> };
}

function writeDecimalFields() {
  const document = JSON.parse(readFileSync(input, "utf8")) as OpenApiDocument;
  const names = new Set<string>();
  const visited = new Set<string>();

  function collect(node: SchemaNode | undefined) {
    if (!node) {
      return;
    }
    if (node.$ref) {
      const name = node.$ref.split("/").at(-1) ?? "";
      if (!visited.has(name)) {
        visited.add(name);
        collect(document.components.schemas[name]);
      }
      return;
    }
    for (const [name, property] of Object.entries(node.properties ?? {})) {
      if (property.format === "decimal") {
        names.add(name);
      }
      collect(property);
    }
    collect(node.items);
    for (const variant of node.oneOf ?? []) {
      collect(variant);
    }
  }

  for (const operations of Object.values(document.paths)) {
    for (const operation of Object.values(operations)) {
      for (const media of Object.values(operation.requestBody?.content ?? {})) {
        collect(media.schema);
      }
    }
  }

  const lines = [...names].toSorted().map((name) => `  "${name}",`);
  writeFileSync(
    decimalFieldsFile,
    [
      "/**",
      " * Generated by orval.config.ts from every `format: decimal` request body property in the OpenAPI spec.",
      " * Do not edit manually.",
      " */",
      "export const decimalFields: ReadonlySet<string> = new Set([",
      ...lines,
      "]);",
      "",
    ].join("\n"),
  );
}

export default defineConfig({
  api: {
    input,
    output: {
      mode: "tags-split",
      client: "react-query",
      clean: true,
      target: "./src/api/generated",
      schemas: "./src/api/generated/model",
      mock: {
        generators: [{ type: "msw", baseUrl: "*", delay: false }],
      },
      override: {
        query: {
          useSuspenseQuery: true,
          signal: true,
        },
        mutator: {
          path: "./src/api/client.ts",
          name: "customFetch",
        },
        fetch: {
          includeHttpResponseReturnType: false,
        },
      },
    },
    hooks: {
      afterAllFilesWrite: [writeDecimalFields, format],
    },
  },
  zod: {
    input,
    output: {
      mode: "tags-split",
      client: "zod",
      clean: true,
      target: "./src/api/schemas",
      fileExtension: ".zod.ts",
    },
    hooks: {
      afterAllFilesWrite: format,
    },
  },
});
