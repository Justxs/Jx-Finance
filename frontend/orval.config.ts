import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { defineConfig } from "orval";
import { z } from "zod";

const input = "./openapi.json";
const decimalFieldsFile = "./src/api/generated/decimal-fields.ts";

function formatFolder(folder: string) {
  return function format() {
    execSync(`oxfmt ${folder}`, { stdio: "inherit" });
  };
}

interface SchemaNode {
  $ref?: string;
  format?: string;
  properties?: Record<string, SchemaNode>;
  items?: SchemaNode;
  oneOf?: SchemaNode[];
}

interface Operation {
  requestBody?: { content?: Record<string, { schema?: SchemaNode }> };
}

interface SpecDocument {
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, SchemaNode> };
}

const schemaNode: z.ZodType<SchemaNode> = z.lazy(() =>
  z.object({
    $ref: z.string().optional(),
    format: z.string().optional(),
    properties: z.record(z.string(), schemaNode).optional(),
    items: schemaNode.optional(),
    oneOf: z.array(schemaNode).optional(),
  }),
);

const operationNode = z.object({
  requestBody: z
    .object({
      content: z.record(z.string(), z.object({ schema: schemaNode.optional() })).optional(),
    })
    .optional(),
});

const specDocument = z.object({
  paths: z.record(z.string(), z.record(z.string(), operationNode)),
  components: z.object({ schemas: z.record(z.string(), schemaNode) }),
});

function writeDecimalFields() {
  const document: SpecDocument = specDocument.parse(JSON.parse(readFileSync(input, "utf8")));
  const names = new Set<string>();
  const visited = new Set<string>();

  function collect(node: SchemaNode | undefined) {
    if (!node) {
      return;
    }
    if (node.$ref) {
      const name = node.$ref.split("/").at(-1) ?? "";
      if (!visited.has(name)) {
        visited.add(name);
        collect(document.components.schemas[name]);
      }
      return;
    }
    for (const [name, property] of Object.entries(node.properties ?? {})) {
      if (property.format === "decimal") {
        names.add(name);
      }
      collect(property);
    }
    collect(node.items);
    for (const variant of node.oneOf ?? []) {
      collect(variant);
    }
  }

  for (const operations of Object.values(document.paths)) {
    for (const operation of Object.values(operations)) {
      for (const media of Object.values(operation.requestBody?.content ?? {})) {
        collect(media.schema);
      }
    }
  }

  const lines = [...names].toSorted((a, b) => a.localeCompare(b)).map((name) => `  "${name}",`);
  writeFileSync(
    decimalFieldsFile,
    [
      "/**",
      " * Generated by orval.config.ts from every `format: decimal` request body property in the OpenAPI spec.",
      " * Do not edit manually.",
      " */",
      "export const decimalFields: ReadonlySet<string> = new Set([",
      ...lines,
      "]);",
      "",
    ].join("\n"),
  );
}

const plainQueryOperations = [
  "GetCurrencies",
  "GetExchangeRate",
  "GetPublicSettings",
  "GetSecurities",
  "GetSettings",
  "GetTransfers",
  "Me",
];

function operationName(operation: object, _route: string, verb: string) {
  const id =
    "operationId" in operation && typeof operation.operationId === "string"
      ? operation.operationId
      : "";
  const name = verb === "get" && /^Get[A-Z]/.test(id) ? id.slice(3) : id;
  return name.charAt(0).toLowerCase() + name.slice(1);
}

const decimalPattern = "^-?\\d+(\\.\\d{1,8})?$";

function describeDecimals(node: unknown) {
  if (Array.isArray(node)) {
    for (const item of node) {
      describeDecimals(item);
    }
    return;
  }
  if (typeof node !== "object" || node === null) {
    return;
  }
  const isDecimal = "format" in node && node.format === "decimal";
  const hasPattern = "pattern" in node && node.pattern !== undefined;
  if (isDecimal && !hasPattern) {
    Object.assign(node, { pattern: decimalPattern });
  }
  for (const value of Object.values(node)) {
    describeDecimals(value);
  }
}

function forValidation<TDocument extends { paths?: object; components?: object }>(
  document: TDocument,
): TDocument {
  const spec = structuredClone(document);
  describeDecimals(spec.components);
  spec.paths = {
    ...spec.paths,
    "/__contract/problem-details": {
      get: {
        operationId: "GetProblemDetails",
        tags: ["Problems"],
        responses: {
          "200": {
            description: "Shape of every application/problem+json failure body.",
            content: {
              "application/json": { schema: { $ref: "#/components/schemas/ProblemDetails" } },
            },
          },
        },
      },
    },
  };
  return spec;
}

